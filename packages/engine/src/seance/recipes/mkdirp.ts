/**
 * mkdirp -> fs.mkdirSync(path, { recursive: true }) (JavaScript, native, file system effects).
 *
 * Why this pair: the function is all side effects, so the séance compares what ends up on disk
 * (the tree, the modes) as well as the answer. Both sides run in identical temporary directories.
 */

import type { KnownDifference, SeanceBundle, SeanceFile } from '../../types.js';
import { callsNote, jsProjectCalls } from '../examples.js';
import { renderReadme } from '../readme.js';
import { makeBundle, type Mutant, type Recipe, type RecipeContext } from '../recipe.js';

const DIR = 'seance/mkdirp';

export const MKDIRP_KNOWN: KnownDifference[] = [
  {
    input: 'mkdirp.sync("")',
    old: 'undefined (the empty path means the current directory, which exists)',
    naive: 'throws ENOENT',
    handled: 'Reproduced: the replacement resolves the path first, like mkdirp.',
  },
  {
    input: 'mkdirp.sync(dir, 0o700)',
    old: 'creates the directories with mode 0o700 (a number is the mode)',
    naive: 'a number is not a valid option: the mode is ignored',
    handled: 'Reproduced: the replacement turns a number or { mode } into the mode option.',
  },
];

function replacementSource(): string {
  return [
    '// Replacement for mkdirp. Generated by Necromancer (recipe "mkdirp").',
    '// Dependency-free: fs.mkdir with { recursive: true }. Use mkdirpSync where you used mkdirp.sync,',
    '// and mkdirp where you used mkdirp (it returns a promise, as mkdirp 1.x does).',
    "import fs from 'node:fs';",
    "import path from 'node:path';",
    '',
    '// mkdirp takes a mode number, a mode string or { mode }.',
    "const modeOf = (opts) => (typeof opts === 'number' || typeof opts === 'string' ? opts : opts && opts.mode);",
    'const optionsFor = (opts) => {',
    '  const mode = modeOf(opts);',
    '  return mode === undefined ? { recursive: true } : { recursive: true, mode };',
    '};',
    '',
    '// mkdirp resolves the path first: "" means the current directory, relative paths use the cwd.',
    '// Returns the first directory that was created, or undefined when all of them existed.',
    'export function mkdirpSync(dir, opts) {',
    '  return fs.mkdirSync(path.resolve(dir), optionsFor(opts));',
    '}',
    '',
    'export async function mkdirp(dir, opts) {',
    '  return fs.promises.mkdir(path.resolve(dir), optionsFor(opts));',
    '}',
    '',
  ].join('\n');
}

function testSource(projectCalls: string[]): string {
  return [
    '// Séance: mkdirp -> fs.mkdir recursive. Generated by Necromancer (recipe "mkdirp").',
    '// Run: npx vitest run seance/mkdirp',
    '//',
    '// For each generated situation (existing folders and files, a target path, an optional mode) the',
    '// séance builds the same starting tree twice, calls mkdirp in one and the replacement in the',
    '// other, and compares: the returned path (relative to the tree), the error class and code, and',
    '// the whole resulting tree (names, kinds, folder modes). Compared after the umask is applied.',
    "import fs from 'node:fs';",
    "import os from 'node:os';",
    "import path from 'node:path';",
    "import { describe, it, expect, afterAll } from 'vitest';",
    "import fc from 'fast-check';",
    "import mkdirpOld from 'mkdirp';",
    "import { mkdirpSync, mkdirp as mkdirpNew } from './replacement.mjs';",
    '',
    "const root = fs.mkdtempSync(path.join(os.tmpdir(), 'seance-mkdirp-'));",
    'afterAll(() => fs.rmSync(root, { recursive: true, force: true }));',
    'let counter = 0;',
    '',
    '// The starting tree: folders and files, as lists of path segments.',
    "const name = fc.constantFrom('a', 'b', 'c', 'x y', '\\u00e9', 'd.e');",
    'const segs = fc.array(name, { minLength: 1, maxLength: 3 });',
    "const entry = fc.record({ kind: fc.constantFrom('dir', 'file'), segs });",
    'const tree = fc.array(entry, { maxLength: 4 });',
    "// A target is a list of segments; '' and '.' produce // and /./ inside the path.",
    "const targetSegs = fc.array(fc.oneof(name, fc.constantFrom('', '.')), { minLength: 1, maxLength: 5 });",
    "const trailing = fc.constantFrom('', '/');",
    'const mode = fc.constantFrom(undefined, 0o700, 0o755, { mode: 0o750 }, { mode: 0o700 });',
    '',
    'function build(base, entries) {',
    '  fs.mkdirSync(base, { recursive: true });',
    '  for (const e of entries) {',
    '    const p = path.join(base, ...e.segs);',
    "    try { if (e.kind === 'dir') fs.mkdirSync(p, { recursive: true }); else { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, 'x'); } } catch { /* a file may be in the way: same in both trees */ }",
    '  }',
    '}',
    '',
    'function snapshot(base) {',
    '  const out = [];',
    '  const walk = (dir) => {',
    '    for (const n of fs.readdirSync(dir).sort()) {',
    '      const p = path.join(dir, n);',
    '      const st = fs.statSync(p);',
    "      out.push([path.relative(base, p), st.isDirectory() ? 'dir' : 'file', st.isDirectory() ? st.mode & 0o777 : null]);",
    '      if (st.isDirectory()) walk(p);',
    '    }',
    '  };',
    '  walk(base);',
    '  return out;',
    '}',
    '',
    "const rel = (base, made) => (typeof made === 'string' ? path.relative(base, made) : made);",
    'const errorOf = (e) => ({ error: e && e.constructor ? e.constructor.name : typeof e, code: e && e.code });',
    '',
    'function sideBySide(entries, target, opts, runOld, runNew) {',
    '  const id = ++counter;',
    "  const a = path.join(root, id + 'a');",
    "  const b = path.join(root, id + 'b');",
    '  build(a, entries);',
    '  build(b, entries);',
    '  const one = (base, fn) => { try { return { ok: true, made: rel(base, fn(path.join(base, target), opts)) }; } catch (e) { return { ok: false, ...errorOf(e) }; } };',
    '  const x = one(a, runOld);',
    '  const y = one(b, runNew);',
    '  return [{ ...x, tree: snapshot(a) }, { ...y, tree: snapshot(b) }];',
    '}',
    '',
    "describe('seance: mkdirp -> fs.mkdir recursive', () => {",
    "  it('mkdirp.sync and mkdirpSync leave the same tree and return the same path', () => {",
    '    fc.assert(',
    '      fc.property(tree, targetSegs, trailing, mode, (entries, t, slash, m) => {',
    "        const target = t.join('/') + slash;",
    '        const [x, y] = sideBySide(entries, target, m, (p, o) => mkdirpOld.sync(p, o), (p, o) => mkdirpSync(p, o));',
    '        expect(y).toEqual(x);',
    '      }),',
    '      { numRuns: 300 },',
    '    );',
    '  });',
    '',
    "  it('mkdirp (promise) and the async replacement leave the same tree and return the same path', async () => {",
    '    await fc.assert(',
    '      fc.asyncProperty(tree, targetSegs, mode, async (entries, t, m) => {',
    "        const target = t.join('/');",
    '        const id = ++counter;',
    "        const a = path.join(root, id + 'a'); const b = path.join(root, id + 'b');",
    '        build(a, entries); build(b, entries);',
    '        const one = async (base, fn) => { try { return { ok: true, made: rel(base, await fn(path.join(base, target), m)) }; } catch (e) { return { ok: false, ...errorOf(e) }; } };',
    '        const x = await one(a, (p, o) => mkdirpOld(p, o));',
    '        const y = await one(b, (p, o) => mkdirpNew(p, o));',
    '        expect({ ...y, tree: snapshot(b) }).toEqual({ ...x, tree: snapshot(a) });',
    '      }),',
    '      { numRuns: 100 },',
    '    );',
    '  });',
    '',
    "  it('wrong argument types fail with the same error class', () => {",
    '    fc.assert(',
    '      fc.property(fc.constantFrom(null, undefined, 1, {}, [], true), (bad) => {',
    '        const run = (fn) => { try { fn(bad); return { ok: true }; } catch (e) { return { ok: false, error: e && e.constructor ? e.constructor.name : typeof e }; } };',
    '        expect(run((p) => mkdirpSync(p))).toEqual(run((p) => mkdirpOld.sync(p)));',
    '      }),',
    '    );',
    '  });',
    '',
    "  it('the empty path means the current directory, as in mkdirp', () => {",
    '    expect(mkdirpOld.sync("")).toBeUndefined();',
    '    expect(mkdirpSync("")).toBeUndefined();',
    '    expect(() => fs.mkdirSync("", { recursive: true })).toThrow(); // the naive call',
    '  });',
    '',
    "  it('a mode given as a number is applied; the naive call ignores it', () => {",
    "    const a = path.join(root, 'mode-old/x/y'); const b = path.join(root, 'mode-new/x/y'); const c = path.join(root, 'mode-naive/x/y');",
    '    mkdirpOld.sync(a, 0o700); mkdirpSync(b, 0o700); fs.mkdirSync(c, { recursive: true, mode: undefined });',
    '    expect(fs.statSync(b).mode & 0o777).toBe(fs.statSync(a).mode & 0o777);',
    '    expect(fs.statSync(a).mode & 0o777).toBe(0o700 & ~process.umask());',
    '  });',
    '',
    ...projectCalls,
    "  it('the replacement answers like mkdirp on the paths this project uses', () => {",
    '    for (const [p] of projectCalls) {',
    "      if (typeof p !== 'string') continue;",
    '      const rootOld = path.join(root, "own-old"); const rootNew = path.join(root, "own-new");',
    '      fs.mkdirSync(rootOld, { recursive: true }); fs.mkdirSync(rootNew, { recursive: true });',
    '      const rel2 = p.replace(/^\\/+/, "");',
    '      const x = mkdirpOld.sync(path.join(rootOld, rel2)); const y = mkdirpSync(path.join(rootNew, rel2));',
    '      expect(rel(rootNew, y)).toEqual(rel(rootOld, x));',
    '    }',
    '  });',
    '});',
    '',
  ].join('\n');
}

function build(ctx: RecipeContext): SeanceBundle {
  const pick = (m: string): boolean => m === 'sync' || m === 'default';
  const files: SeanceFile[] = [
    {
      path: `${DIR}/seance.test.mjs`,
      content: testSource(jsProjectCalls(ctx.usage, pick, 'projectCalls', '  ')),
      role: 'test',
    },
    { path: `${DIR}/replacement.mjs`, content: replacementSource(), role: 'replacement' },
  ];
  const compares = [
    'The returned path (relative to the test tree) or the error class and code; and the whole resulting tree: names, file or folder, folder modes.',
    'Both sides start from identical generated trees (folders, files that may be in the way) and the same target: nested names, "." and empty segments, trailing slash, with and without a mode.',
    'Async: the promise form of mkdirp against the async replacement. Not covered: custom fs implementations passed as opts.fs, and the callback form of mkdirp 0.5.',
    callsNote(ctx.usage, pick),
  ];
  const install = ['npm install --save-dev vitest fast-check'];
  const run = 'npx vitest run seance/mkdirp';
  files.push({
    path: `${DIR}/README.md`,
    role: 'readme',
    content: renderReadme({
      title: 'mkdirp to fs.mkdir recursive',
      recipe: 'mkdirp',
      files: [
        {
          path: `${DIR}/seance.test.mjs`,
          what: 'the differential property test (compares files on disk)',
        },
        { path: `${DIR}/replacement.mjs`, what: 'mkdirpSync and mkdirp with the old answers' },
      ],
      install,
      run,
      compares,
      known: MKDIRP_KNOWN,
    }),
  });
  return makeBundle({
    language: 'javascript',
    recipe: 'mkdirp',
    title: 'mkdirp to fs.mkdir recursive',
    files,
    install,
    run,
    compares,
    knownDifferences: MKDIRP_KNOWN,
    members: ['default', 'sync'],
  });
}

function mutants(): Mutant[] {
  const path = `${DIR}/replacement.mjs`;
  return [
    {
      id: 'naive-mkdir-recursive',
      description: 'calls fs.mkdirSync(dir, { recursive: true }) and ignores the mode',
      files: [
        {
          path,
          role: 'replacement',
          content: [
            "import fs from 'node:fs';",
            'export function mkdirpSync(dir) { return fs.mkdirSync(dir, { recursive: true }); }',
            'export async function mkdirp(dir) { return fs.promises.mkdir(dir, { recursive: true }); }',
            '',
          ].join('\n'),
        },
      ],
    },
    {
      id: 'returns-last-directory',
      description: 'returns the last directory instead of the first one created',
      files: [
        {
          path,
          role: 'replacement',
          content: replacementSource()
            .replace(
              'return fs.mkdirSync(path.resolve(dir), optionsFor(opts));',
              'const made = fs.mkdirSync(path.resolve(dir), optionsFor(opts)); return made === undefined ? made : path.resolve(dir);',
            )
            .replace(
              'return fs.promises.mkdir(path.resolve(dir), optionsFor(opts));',
              'const made = await fs.promises.mkdir(path.resolve(dir), optionsFor(opts)); return made === undefined ? made : path.resolve(dir);',
            ),
        },
      ],
    },
  ];
}

