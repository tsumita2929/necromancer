import type { KnownDifference } from '../types.js';
import { codeCell, comment } from './emit.js';

export interface ReadmeInput {
  title: string;
  recipe: string | null;
  files: Array<{ path: string; what: string }>;
  install: string[];
  run: string;
  compares: string[];
  known: KnownDifference[];
  notes?: string[];
}

/** README.md for a séance folder. All text is flattened; code samples come from the recipe. */
export function renderReadme(r: ReadmeInput): string {
  const out: string[] = [
    `# Séance: ${comment(r.title)}`,
    '',
    `Generated by Necromancer${r.recipe ? ` (recipe \`${comment(r.recipe, 40)}\`)` : ' (generic template)'}.`,
    '',
    'A séance asks the old package and its replacement the same generated questions and fails on',
    'any different answer. Run it before you switch, and keep it while you migrate.',
    '',
    '## Files',
    '',
    ...r.files.map((f) => `- \`${comment(f.path, 80)}\`: ${comment(f.what, 160)}`),
    '',
    '## Run',
    '',
    '```sh',
    ...r.install,
    r.run,
    '```',
    '',
    'The old package stays installed until the last step: the séance asks it the questions.',
    '',
    '## What it compares',
    '',
    ...r.compares.map((c) => `- ${comment(c, 240)}`),
    '',
  ];
  if (r.known.length > 0) {
    out.push(
      '## Known differences',
      '',
      'Found by running the séance against the real packages.',
      '',
    );
    out.push(
      '| Input | Old package | Naive replacement | In the generated replacement |',
      '| --- | --- | --- | --- |',
    );
    for (const k of r.known) {
      const cell = (t: string) => codeCell(t, 160);
      out.push(
        `| ${cell(k.input)} | ${cell(k.old)} | ${cell(k.naive)} | ${comment(k.handled, 120).replace(/\|/g, '/')} |`,
      );
    }
    out.push('');
  }
  if (r.notes && r.notes.length > 0)
    out.push('## Notes', '', ...r.notes.map((n) => `- ${comment(n, 240)}`), '');
  return `${out.join('\n')}\n`;
}
