// Turns docs/research/successors.json (the researched ways out for the census's dead packages) into the
// engine's offline data file src/researched.ts.
//
//   node scripts/build-successors-data.mjs          writes src/researched.ts
//   node scripts/build-successors-data.mjs --check  exits 1 when src/researched.ts is out of date
//
// Only entries with at least one successor are kept. A successor whose mapping came from a README notice
// or a migration guide gets the source "readme" (the research records it as "curated" with a url).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const input = join(here, '..', '..', '..', 'docs', 'research', 'successors.json');
const output = join(here, '..', 'src', 'researched.ts');

export function build(json) {
  const rows = [];
  for (const entry of json.entries) {
    if (!Array.isArray(entry.successors) || entry.successors.length === 0) continue;
    const fromReadme = ['readme-notice', 'migration-guide'].includes(entry.mapping?.source);
    rows.push({
      ecosystem: entry.ecosystem,
      name: entry.name,
      confidence: entry.mapping?.confidence ?? 'medium',
      successors: entry.successors.map((s) => ({
        name: s.name,
        kind: s.kind,
        reason: s.reason,
        source: s.source === 'curated' && fromReadme ? 'readme' : s.source,
        ...(s.url ? { url: s.url } : {}),
      })),
    });
  }
  rows.sort((a, b) => `${a.ecosystem}:${a.name}`.localeCompare(`${b.ecosystem}:${b.name}`));
  return [
    '// Generated by scripts/build-successors-data.mjs from docs/research/successors.json. Do not edit.',
    `// Checked on ${json.checkDate}. ${rows.length} dead packages with a researched way out.`,
    '',
    "import type { Ecosystem, SourceId, Successor } from './types.js';",
    '',
    'export interface ResearchedEntry {',
    '  ecosystem: Ecosystem;',
    '  name: string;',
    "  confidence: 'high' | 'medium' | 'low';",
    "  successors: Array<Omit<Successor, 'ecosystem' | 'confidence'> & { source: SourceId }>;",
    '}',
    '',
    `export const RESEARCHED_ON = ${JSON.stringify(json.checkDate)};`,
    '',
    `export const RESEARCHED: readonly ResearchedEntry[] = ${JSON.stringify(rows, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = build(JSON.parse(readFileSync(input, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = readFileSync(output, 'utf8');
    // The file is formatted by Prettier after it is written, so compare after the same formatting.
    const { format } = await import('prettier');
    const formatted = await format(text, {
      parser: 'typescript',
      singleQuote: true,
      printWidth: 100,
      trailingComma: 'all',
    });
    if (current !== formatted) {
      console.error('src/researched.ts is out of date: run node scripts/build-successors-data.mjs');
      process.exit(1);
    }
    console.log('src/researched.ts is up to date');
  } else {
    writeFileSync(output, text);
    console.log(`wrote ${output}`);
  }
}
